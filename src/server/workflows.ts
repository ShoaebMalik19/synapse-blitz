export type WorkflowStatus = "DRAFT" | "APPROVAL_REQUIRED" | "APPROVED" | "ACTIVE" | "COMPLETED" | "FAILED" | "CANCELLED";

export interface WorkflowRow {
  id: string;
  goal: string;
  status: WorkflowStatus;
  planner: string;
  plan_json: string;
  plan_hash: string;
  budget_json: string;
  owner: string;
  approved_at: number | null;
  settlement_status: string;
  settlement_note: string | null;
  created_at: number;
  updated_at: number;
}

export function getWorkflow(id: string, db: DB = getDb()) {
  return db.prepare(`SELECT * FROM workflows WHERE id = ?`).get(id) as WorkflowRow | undefined;
}

export function setWorkflowStatus(id: string, status: WorkflowStatus, db: DB = getDb()) {
  db.prepare(`UPDATE workflows SET status = ?, updated_at = ? WHERE id = ?`).run(status, now(), id);
}

export async function createWorkflow(goal: string, budget: BudgetInput, owner: string, db: DB = getDb()) {
  seedWorkers(db);
  const { plan, planner, notes } = await generatePlan(goal, budget);
  const id = newId("wf");
  const planHash = sha256Hex(stableStringify(plan));
  const t = now();
  db.transaction(() => {
    db.prepare(
      `INSERT INTO workflows (id, goal, status, planner, plan_json, plan_hash, budget_json, owner, created_at, updated_at)
       VALUES (?,?,?,?,?,?,?,?,?,?)`,
    ).run(id, goal, "APPROVAL_REQUIRED", planner, JSON.stringify(plan), planHash, JSON.stringify(toStoredBudget(budget)), owner, t, t);
    insertPlanTasks(id, plan.tasks, db);
    emit(id, "workflow.created", `Workflow created; ${plan.tasks.length}-task DAG generated by ${planner}`, { data: { planHash }, db });
    for (const n of notes) emit(id, "planner.note", n, { level: "warn", db });
    emit(id, "workflow.approval_required", "Plan validated (acyclic, capabilities allowlisted, within budget). Awaiting operator approval.", { db });
  })();
  return id;
}

export function approveWorkflow(id: string, opts: { failureDrill: boolean; approveHighValue: boolean }, db: DB = getDb()) {
  return db.transaction(() => {
    const wf = getWorkflow(id, db);
    if (!wf) throw new HttpError(404, "workflow not found");
    if (wf.status !== "APPROVAL_REQUIRED") throw new HttpError(409, `workflow is ${wf.status}, not awaiting approval`);
    const budget = JSON.parse(wf.budget_json) as StoredBudget;
    budget.highValueApproved = opts.approveHighValue;
    db.prepare(`UPDATE workflows SET status='APPROVED', approved_at=?, budget_json=?, updated_at=? WHERE id=?`).run(now(), JSON.stringify(budget), now(), id);
    emit(id, "workflow.approved", `Operator approved plan and budget${opts.approveHighValue ? " (high-value purchases pre-approved)" : ""}`, { level: "success", db });
    if (opts.failureDrill) armFailure(id, db);
    return getWorkflow(id, db)!;
  })();
}

export class HttpError extends Error {
  constructor(public status: number, message: string) {
    super(message);
  }
}

/** Arm a controlled crash of Worker A on the research task, fired right after its next checkpoint. */
export function armFailure(id: string, db: DB = getDb()) {
  const wf = getWorkflow(id, db);
  if (!wf) throw new HttpError(404, "workflow not found");
  if (["COMPLETED", "FAILED", "CANCELLED"].includes(wf.status)) throw new HttpError(409, `workflow is ${wf.status}`);
  const task = getTasks(id, db).find((t) => t.capability === "research" && t.status !== "COMPLETED" && t.status !== "FAILED");
  if (!task) throw new HttpError(409, "no unfinished research task left to fail over");
  if (task.current_worker && task.current_worker !== "worker-a")
    throw new HttpError(409, `research task is running on ${task.current_worker}; failure drill targets worker-a`);
  const existing = db.prepare(`SELECT id FROM fault_injections WHERE workflow_id=? AND task_id=? AND status='ARMED'`).get(id, task.task_id);
  if (existing) throw new HttpError(409, "a failure is already armed for this task");
  const fid = newId("fault");
  db.prepare(`INSERT INTO fault_injections (id, workflow_id, task_id, worker_id, mode, status, created_at) VALUES (?,?,?,?,?,?,?)`).run(
    fid,
    id,
    task.task_id,
    "worker-a",
    "CRASH_AFTER_CHECKPOINT",
    "ARMED",
    now(),
  );
  emit(id, "fault.armed", `Failure injection armed: Worker A will crash after its next checkpoint on "${task.title}"`, {
    taskId: task.task_id,
    level: "warn",
    data: { faultId: fid },
    db,
  });
  return { faultId: fid, taskId: task.task_id };
}

export function cancelWorkflow(id: string, db: DB = getDb()) {
  const wf = getWorkflow(id, db);
  if (!wf) throw new HttpError(404, "workflow not found");
  if (["COMPLETED", "FAILED", "CANCELLED"].includes(wf.status)) throw new HttpError(409, `workflow is already ${wf.status}`);
  db.transaction(() => {
    setWorkflowStatus(id, "CANCELLED", db);
    db.prepare(`UPDATE workflow_tasks SET status='CANCELLED', updated_at=? WHERE workflow_id=? AND status NOT IN ('COMPLETED','FAILED')`).run(now(), id);
    emit(id, "workflow.cancelled", "Workflow cancelled by operator", { level: "warn", db });
  })();
}

export function listWorkflows(db: DB = getDb()) {
  return db
    .prepare(
      `SELECT w.id, w.goal, w.status, w.planner, w.settlement_status, w.created_at, w.updated_at,
        (SELECT COUNT(*) FROM workflow_tasks t WHERE t.workflow_id = w.id) AS task_count,
        (SELECT COUNT(*) FROM workflow_tasks t WHERE t.workflow_id = w.id AND t.status='COMPLETED') AS completed_count
       FROM workflows w ORDER BY w.created_at DESC LIMIT 50`,
    )
    .all();
}

export function workflowView(id: string, db: DB = getDb()) {
  const wf = getWorkflow(id, db);
  if (!wf) return null;
  const tasks = getTasks(id, db).map((t) => ({
    taskId: t.task_id,
    title: t.title,
    description: t.description,
    capability: t.capability,
    dependencies: JSON.parse(t.dependencies_json) as string[],
    eligibleWorkers: JSON.parse(t.eligible_workers_json),
    estimatedCost: JSON.parse(t.estimated_cost_json),
    maxCost: JSON.parse(t.max_cost_json),
    retryLimit: t.retry_limit,
    timeoutMs: t.timeout_ms,
    verificationCriteria: JSON.parse(t.verification_json),
    status: t.status,
    attempts: t.attempts,
    currentWorker: t.current_worker,
    currentStep: t.current_step,
    leaseExpiresAt: t.lease_expires_at,
    resultHash: t.result_hash,
    resultArtifactId: t.result_artifact_id,
    error: t.error,
    updatedAt: t.updated_at,
  }));
  const attempts = db.prepare(`SELECT * FROM task_attempts WHERE workflow_id = ? ORDER BY started_at`).all(id);
  const checkpoints = db
    .prepare(`SELECT id, task_id, attempt_id, worker_id, seq, schema_version, completed_steps_json, payment_op_ids_json, state_hash, created_at FROM task_checkpoints WHERE workflow_id = ? ORDER BY created_at`)
    .all(id);
  const faults = db.prepare(`SELECT * FROM fault_injections WHERE workflow_id = ? ORDER BY created_at`).all(id);
  return {
    workflow: {
      id: wf.id,
      goal: wf.goal,
      status: wf.status,
      planner: wf.planner,
      plan: JSON.parse(wf.plan_json) as Plan,
      planHash: wf.plan_hash,
      budget: JSON.parse(wf.budget_json) as StoredBudget,
      approvedAt: wf.approved_at,
      settlementStatus: wf.settlement_status,
      settlementNote: wf.settlement_note,
      createdAt: wf.created_at,
      updatedAt: wf.updated_at,
    },
    tasks,
    attempts,
    checkpoints,
    faults,
    budget: budgetSummary(id, db),
  };
}

export function paymentsView(id: string, db: DB = getDb()) {
  const payments = (db.prepare(`SELECT * FROM payment_operations WHERE workflow_id = ? ORDER BY created_at`).all(id) as PaymentOp[]).map((p) => ({
    ...p,
    verification: p.verification_json ? JSON.parse(p.verification_json) : null,
    verification_json: undefined,
  }));
  const escrow = escrowOps(id, db).map((e) => ({ ...e, verification: e.verification_json ? JSON.parse(e.verification_json) : null, verification_json: undefined }));
  return { payments, escrow, budget: budgetSummary(id, db), escrowContract: env().MONAD_ESCROW_ADDRESS ? { address: env().MONAD_ESCROW_ADDRESS, explorer: explorerAddress(env().MONAD_ESCROW_ADDRESS!) } : null };
}

export async function resultView(id: string, db: DB = getDb()) {
  const view = workflowView(id, db);
  if (!view) return null;
  const synth = view.tasks.find((t) => t.capability === "synthesis");
  const art = synth?.resultArtifactId
    ? (db.prepare(`SELECT content, sha256, created_at FROM artifacts WHERE id = ?`).get(synth.resultArtifactId) as { content: string; sha256: string; created_at: number })
    : null;
  const output = art ? (JSON.parse(art.content) as { markdown: string; sources: { id: string; title: string; url: string; kind: string }[] }) : null;
  const verifications = db
    .prepare(`SELECT task_id, content FROM artifacts WHERE workflow_id = ? AND kind = 'verification-report' ORDER BY created_at`)
    .all(id) as { task_id: string; content: string }[];
  let onchain = null;
  try {
    onchain = await readEscrowTask(id);
  } catch {
    onchain = null;
  }
  return {
    ...view,
    report: output ? { markdown: output.markdown, sources: output.sources, sha256: art!.sha256, createdAt: art!.created_at } : null,
    verifications: verifications.map((v) => ({ taskId: v.task_id, ...JSON.parse(v.content) })),
    ...paymentsView(id, db),
    onchainEscrowTask: onchain,
  };
}
